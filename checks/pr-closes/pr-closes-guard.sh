#!/usr/bin/env bash
# PR, который сделал задачу, обязан её закрыть — и сказать это словом, которое понимает GitHub.
#
# ЗАЧЕМ. В монорепо ais за два дня накопилось шесть сделанных и смерженных задач, которые
# остались открытыми (dippstack/ais: 796, 798, 801, 803, 806, 809). Во всех шести PR написано
# «Закрывает #N». GitHub такую формулировку не читает вовсе — автозакрытие срабатывает
# только на английские `Closes` / `Fixes` / `Resolves` (и их формы). Русская фраза для него
# обычная ссылка, поэтому задача остаётся открытой, и узнаёт об этом в лучшем случае тот,
# кто через неделю удивится длине бэклога.
#
# Поймать это глазами нельзя: PR зелёный, работа в main, всё выглядит законченным. Ровно тот
# случай, про который канон говорит «проверяется машиной, а не памятью».
#
# `dl land` ключевое слово ставит сам. Дыра — в PR, открытых руками через `gh pr create`,
# а это сегодня обычный путь, и тела PR по всему флоту пишутся русской прозой. Дисциплина
# бота-промпта не сработала шесть раз из шести, поэтому проверяет машина.
#
# ПОЧЕМУ ЗДЕСЬ, А НЕ В КАЖДОЙ РЕПЕ. Первая раскатка положила страж копией в ais, yan и
# marketspace, и комментарии трёх копий разошлись в день рождения. Следующая правка регулярки
# была бы тремя правками, и ни одна проверка не покраснела бы, если сделать одну (dippstack/ais#831).
# Теперь это рецепт флота: правится здесь, приезжает всем.
#
# Использование (руками, вне CI):
#   checks/pr-closes/pr-closes-guard.sh --body <файл-с-телом-PR> [--branch <имя-ветки>]
#   checks/pr-closes/pr-closes-guard.sh --body-text "<тело>" [--branch <имя-ветки>]
#
# Выход: 0 — порядок, 1 — есть чем закрыть, но не закрыто (сообщение говорит, что дописать).
set -uo pipefail

body=""
branch=""
while [ $# -gt 0 ]; do
  case "$1" in
    # Файл обязан существовать. `cat ... || true` тут был бы худшим из возможных поведений:
    # опечатка в пути или неавторизованный `gh` дали бы пустое тело, а пустое тело без ветки —
    # бодрый зелёный вердикт. Ручная проверка, которая всегда зелёная, вреднее отсутствующей.
    --body)      [ -f "$2" ] || { echo "⛔ файла с телом PR нет: $2" >&2; exit 2; }
                 body="$(cat "$2")"; shift 2 ;;
    --body-text) body="$2"; shift 2 ;;
    --branch)    branch="$2"; shift 2 ;;
    *) echo "usage: pr-closes-guard.sh --body <файл> | --body-text <текст> [--branch <ветка>]" >&2; exit 2 ;;
  esac
done

# Ключевые слова — те, что GitHub действительно понимает (close/closes/closed, fix/fixes/fixed,
# resolve/resolves/resolved). Список не расширяем «на всякий случай»: страж, требующий слова,
# которое ничего не закрывает, вреднее отсутствующего.
closes_for() {   # closes_for <номер> → 0, если для этого номера есть настоящее ключевое слово
  printf '%s' "$body" | grep -qiE "(clos(e|es|ed)|fix(es|ed)?|resolv(e|es|ed))[[:space:]]*:?[[:space:]]*#$1([^0-9]|\$)"
}
# Кириллицу пишем обоими регистрами явно: `grep -i` в локали C русские буквы не складывает,
# и «Чинит» мимо шаблона «чинит» прошёл бы молча — ровно то, от чего этот страж и заведён.
RU_CLOSES='([Зз]акрывает|[Зз]акроет|[Зз]акрыто|[Чч]инит|[Фф]иксит|[Ии]справляет|[Рр]ешает)'
excused_for() {  # явный отказ закрывать — решение видимое, а не молчаливое
  printf '%s' "$body" | grep -qE "[Нн]е[[:space:]]+закрывает[[:space:]]*:?[[:space:]]*#$1([^0-9]|\$)"
}
# Свой репозиторий нужен ровно для одного: `dippstack/ais#826` в PR самого ais — это НЕ
# чужая задача. Если бы гасило любое полное имя, дыра вернулась бы через написание своего же
# номера полным именем, и вернулась бы тихо. В Actions имя даёт окружение, локально — origin.
self_repo="${GITHUB_REPOSITORY:-$(git config --get remote.origin.url 2>/dev/null \
  | sed -E 's#^(git@[^:]+:|[a-z]+://[^/]+/)##; s#\.git$##')}"

foreign_for() {  # номер назван с ЧУЖИМ репозиторием: `dippstack/ais#788` — задача не наша
  for ref in $(printf '%s' "$body" \
      | grep -oE "[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+#$1([^0-9]|\$)" \
      | sed 's/#.*//' | sort -u); do
    [ "$ref" = "$self_repo" ] || return 0
  done
  return 1
}

missing=""

# 1. Русская закрывающая формулировка — автор СЧИТАЕТ, что закрывает, но GitHub не согласен.
ru_nums="$(printf '%s' "$body" \
  | grep -oE "${RU_CLOSES}[[:space:]]*:?[[:space:]]*#[0-9]+" \
  | grep -oE '#[0-9]+' | tr -d '#' | sort -u)"

# 2. Ветка агентского слайса — именно этим путём пришли все шесть потерянных задач.
# Разделитель после `agent` берём любой: `dl claim` заводит ветку через слэш
# (`agent/826-closes-guard`), а руками и из чужих обвязок приходит дефис — так пришли
# #818, #820 и #821, и первая редакция стража на них молчала бы, потому что ловила только
# слэш. Форма имени ветки не должна решать, увидит страж задачу или нет. Кто именно родил
# дефисную форму, не выяснено; обе легальны намеренно, пока производитель не найден.
#
# ЧУЖОЙ НОМЕР В ИМЕНИ ВЕТКИ. Обычный порядок флота — задача заведена в ais, а правка едет в
# yan или marketspace: ветка называется по чужой задаче, и локальной задачи с таким номером
# просто нет. Так уже было: yan-app/yan-monorepo#575 приехал с ветки `agent/788-ci-edited`,
# а yan#788 не существует вовсе — это dippstack/ais#788. Требовать `Closes #788` там значит
# требовать закрыть чужую или несуществующую задачу, а стража, который требует вранья,
# обходят. Поэтому номер из ветки гасится ещё и квалифицированной ссылкой `репо#N` в теле:
# автор сказал, чья это задача, и сказал видимо. Русскую формулировку в теле это НЕ гасит —
# там автор заявил, что закрывает задачу ЭТОГО репозитория.
#
# Остаток грубости принят: первое число после `agent` считается номером задачи, так что
# ветка `agent/2026-09-sweep` попросит сказать что-нибудь про #2026. Сузить нечем — дата и
# номер выглядят одинаково, — а выход стоит одной честной строки: «Не закрывает #2026: это
# дата в имени ветки». Поведение заперто проверкой, чтобы его меняли осознанно.
br_num=""
case "$branch" in
  agent[/-][0-9]*) br_num="$(printf '%s' "${branch#agent?}" | grep -oE '^[0-9]+')" ;;
esac

for n in $ru_nums; do
  closes_for "$n" && continue
  excused_for "$n" && continue
  missing="$missing $n"
done

if [ -n "$br_num" ]; then
  case " $missing " in
    *" $br_num "*) ;;   # уже назван русской формулировкой — второй раз не повторяем
    *) closes_for "$br_num" || excused_for "$br_num" || foreign_for "$br_num" \
         || missing="$missing $br_num" ;;
  esac
fi

if [ -z "$missing" ]; then
  echo "✓ закрывающие ключевые слова на месте"
  exit 0
fi

echo "⛔ PR не закроет задачу, хотя выглядит так, будто закрывает."
for n in $missing; do
  echo "   #$n — в теле нет ключевого слова, которое понимает GitHub."
done
cat <<'HINT'

   Допиши в тело PR строку (первой — проще всего заметить):
       Closes #<номер>
   «Закрывает #N» GitHub не читает: для него это обычная ссылка, и задача останется
   открытой молча. Понимает только английские Closes / Fixes / Resolves.

   Работа частичная и задачу закрывать не надо — скажи это явно:
       Не закрывает #<номер>: <почему>
   Тогда решение видно в теле PR, а не растворяется в молчании.

   Частый случай — задача едет несколькими слайсами, и этот PR не последний. Тогда закрывать
   родителя рано, и правильный ответ именно второй:
       Не закрывает #<номер>: слайс 2 из 3, остальное отдельными PR
   Дописать `Closes` здесь короче, но это закроет задачу на первом же мерже — молча и не тем.

   Номер в имени ветки — от задачи ЧУЖОГО репозитория (обычное дело: задача в ais, правка
   здесь)? Назови её полным именем, и страж замолчит:
       Часть dippstack/ais#<номер>
HINT
exit 1
