#!/usr/bin/env bash
# Страж закрывающих слов проверяется настоящими телами PR — теми, на которых он и родился.
#
# ЗАЧЕМ ОБЕ ПОЛОВИНЫ. Страж решает судьбу чужого PR: красный гейт останавливает мерж. Значит
# проверять надо не только что он краснеет на потерянной задаче, но и что он МОЛЧИТ там, где
# всё в порядке — иначе его начнут обходить, и он перестанет что-либо значить. Фикстуры ниже
# взяты с реальных PR: #797 («Закрывает #796» — задача осталась открытой) и #800
# («Closes #791» — закрылась сама).
set -uo pipefail
GUARD="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)/pr-closes-guard.sh"
# «Своё» и «чужое» у стража зависит от репозитория, в котором он бежит. Проверки не должны
# зависеть от того, откуда их запустили, поэтому имя задаём явно — и берём yan, потому что
# именно там живёт настоящий случай с чужим номером в имени ветки.
export GITHUB_REPOSITORY="yan-app/yan-monorepo"

fails=0
ok()   { printf '  ок      %s\n' "$1"; }
bad()  { printf '  ПРОВАЛ  %s\n' "$1"; fails=$((fails+1)); }

check() {   # check <ожидаемый код> <описание> <ветка> <тело>
  local want="$1" what="$2" branch="$3" body="$4" got
  "$GUARD" --body-text "$body" --branch "$branch" >/dev/null 2>&1
  got=$?
  if [ "$got" = "$want" ]; then ok "$what"; else bad "$what (ждали код $want, получили $got)"; fi
}

echo "── страж закрывающих ключевых слов"

check 1 "русское «Закрывает #N» краснеет — GitHub его не читает" \
      "agent/796-wt-hook" "Закрывает #796.

Гейт рендера краснел в каждом агентском worktree."

check 0 "английское Closes #N проходит" \
      "agent/791-scenes-by-slug" "Closes #791

Холст отдаёт любую сцену проекта по слагу."

check 0 "Fixes и Resolves — тоже настоящие ключевые слова" \
      "agent/42-bug" "Fixes #42, resolves #43."

check 1 "ветка agent/<N> без единого ключевого слова краснеет" \
      "agent/815-closes-guard" "Тело человеческой прозой, про задачу ни слова."

check 1 "ветка agent-<N> через дефис ловится так же, как через слэш" \
      "agent-813-node-pin" "Тело человеческой прозой, про задачу ни слова."

check 0 "ветка через дефис с настоящим ключевым словом проходит" \
      "agent-813-node-pin" "Closes #813

Версия bun больше не живёт в четырёх местах."

check 0 "явный отказ закрывать гасит стража — решение видно, а не молчит" \
      "agent/815-closes-guard" "Не закрывает #815: это первая половина, вторая уедет отдельным PR."

check 0 "номер из ветки — от чужой задачи: квалифицированная ссылка гасит стража" \
      "agent/788-ci-edited" "Часть dippstack/ais#788: рецепты CI флота красят гейт за заголовок PR."

check 1 "а русская формулировка чужой ссылкой не гасится — тут заявлено закрытие СВОЕЙ" \
      "chore/none" "Закрывает #788. Ссылка рядом: dippstack/ais#788."

check 1 "своя же задача полным именем стража НЕ гасит — иначе дыра вернулась бы тихо" \
      "agent/788-ci-edited" "Часть yan-app/yan-monorepo#788: правка гейта заголовка."

check 1 "первое число после agent страж считает номером задачи — грубо и намеренно" \
      "agent/2026-09-sweep" "Дворник по хранилищу Actions, задачи нет."

check 0 "и выход из ложного красного стоит одной честной строки" \
      "agent/2026-09-sweep" "Не закрывает #2026: это дата в имени ветки, не номер задачи."

check 0 "PR без задач вообще страж не трогает" \
      "chore/bump-deps" "Подняли зависимости, задачи нет."

check 1 "ссылка на задачу словом «Чинит» краснеет так же" \
      "chore/fix" "Чинит #123 — гейт не видел симлинк."

check 0 "номер внутри другого номера не путает: #7910 не закрывает #791" \
      "chore/none" "Closes #7910"

check 1 "и тот же случай с ветки: #791 не считается закрытым из-за #7910" \
      "agent/791-scenes" "Closes #7910"

"$GUARD" --body /nonexistent/pr-body.txt >/dev/null 2>&1
[ $? = 2 ] && ok "нет файла с телом — код 2, а не зелёный вердикт на пустом теле" \
           || bad "нет файла с телом: ждали код 2"

echo
[ "$fails" = 0 ] && { echo "страж закрывающих слов: все проверки пройдены"; exit 0; }
echo "страж закрывающих слов: провалов $fails"; exit 1
